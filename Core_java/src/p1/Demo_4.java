package p1;

public class Demo_4 {

	
		public static void main(String[] args) {
		int num;
		float b;
		char c;
		String s;  
		
		num = 100; // integer
		
		b = 1.234f; // float
		
		c = 'A'; // character
		
		s = "Hello Java"; // string
		
		System.out.println("Value of num: " + num);
		System.out.println("Value of b: " + b);
		System.out.println("Value of c: " + c);
		System.out.println("Value of s: " + s);
		}

	
}
